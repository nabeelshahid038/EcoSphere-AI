function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      <ThemeInitializer />
      <CommandPalette />
      <PageTransition>
        <Outlet />
      </PageTransition>
      <Toaster richColors position="top-right" closeButton />
    </QueryClientProvider>
  );
}
